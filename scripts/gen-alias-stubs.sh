#!/usr/bin/env bash
# scripts/gen-alias-stubs.sh — resolve declared skill aliases and materialize
# them as generated stub directories under <home-root>/skills/ (ADR-083 D1,
# D2, D9-D14).
#
# Usage:
#   scripts/gen-alias-stubs.sh [--repo-root PATH] [--home-root PATH]
#                              [--sources LIST] [--stack-only]
#                              [--no-purge] [--check]
#
# --sources defaults to "org,stack" — precedence order, highest first (D2:
# resolve(sources) folds the list, first-declaration-wins per word). Phase 1
# recognizes exactly two scope names: "org" -> <home-root>/config/
# aliases.org.json, "stack" -> <home-root>/config/aliases.json. Adding a
# level later is one more recognized scope name here, per D2 — the fold,
# validation, generation and purge logic below are all written against the
# resolved map, never against a named scope.
#
# --stack-only validates <repo-root>/config/aliases.json ONLY (the committed
# stack source, read directly from the checkout — no --home-root needed) and
# writes nothing. This is what CI (lint-skills.yml) uses; org data and the
# materialized tree are both irrelevant to "is the stack's own declaration
# well-formed".
#
# --no-purge (also implied by STACK_INSESSION=1, ADR-083 D16) skips deleting
# any stub whose word left the resolved map. Every word that would have been
# purged is instead recorded in <home-root>/state/alias-pending-purge.json
# and applied by the next run that does not suppress purge.
#
# --check compares the resolved plan against what's on disk under
# <home-root>/skills/ without writing anything: exit 0 if nothing would
# change, exit 1 if a stub would be added, refreshed, or purged. A
# purge deferred by --no-purge/STACK_INSESSION is not drift.
#
# Exit codes: 0 ok | 1 drift (--check only) | 2 usage | 3 malformed source or
# refused overwrite (a directory exists at a stub path without the D12
# generated-file header — never overwritten, never deleted).
#
# Offline (C6): every input here is local file I/O. No network call anywhere
# in this script.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
DEFAULT_REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

REPO_ROOT="$DEFAULT_REPO_ROOT"
HOME_ROOT="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
SOURCES="org,stack"
STACK_ONLY=false
NO_PURGE=false
CHECK=false

usage() {
  cat <<'EOF'
scripts/gen-alias-stubs.sh [--repo-root PATH] [--home-root PATH]
                           [--sources LIST] [--stack-only]
                           [--no-purge] [--check]
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --repo-root)
      [[ $# -ge 2 ]] || { echo "gen-alias-stubs: --repo-root needs a value" >&2; exit 2; }
      REPO_ROOT="$2"; shift 2 ;;
    --home-root)
      [[ $# -ge 2 ]] || { echo "gen-alias-stubs: --home-root needs a value" >&2; exit 2; }
      HOME_ROOT="$2"; shift 2 ;;
    --sources)
      [[ $# -ge 2 ]] || { echo "gen-alias-stubs: --sources needs a value" >&2; exit 2; }
      SOURCES="$2"; shift 2 ;;
    --stack-only) STACK_ONLY=true; shift ;;
    --no-purge) NO_PURGE=true; shift ;;
    --check) CHECK=true; shift ;;
    --help|-h) usage; exit 0 ;;
    *) echo "gen-alias-stubs: unknown arg: $1" >&2; exit 2 ;;
  esac
done

# D16 — an in-session stack update can never strand a word: purge is
# suppressed and deferred, and the deferred set is recorded (never skipped).
if [[ "${STACK_INSESSION:-}" == "1" ]]; then
  NO_PURGE=true
fi

command -v python3 >/dev/null 2>&1 || { echo "gen-alias-stubs: python3 not found" >&2; exit 2; }

python3 - "$REPO_ROOT" "$HOME_ROOT" "$SOURCES" "$STACK_ONLY" "$NO_PURGE" "$CHECK" <<'PYEOF'
import sys, os, re, json, glob

REPO_ROOT, HOME_ROOT, SOURCES_ARG, STACK_ONLY, NO_PURGE, CHECK = sys.argv[1:7]
STACK_ONLY = STACK_ONLY == 'True' or STACK_ONLY == 'true'
NO_PURGE = NO_PURGE == 'True' or NO_PURGE == 'true'
CHECK = CHECK == 'True' or CHECK == 'true'

HEADER_PREFIX = '<!-- generated by scripts/gen-alias-stubs.sh — declared in '
WORD_RE = re.compile(r'^[a-z][a-z0-9-]{0,31}$')
MODE_RE = re.compile(r'^[a-z][a-z0-9-]{0,15}$')
ALLOWED_TOP = {'version', 'aliases'}
ALLOWED_ENTRY = {'target', 'disable', 'mode', 'help', 'description', 'tools'}

# Display path used in the generated-file header and error messages — the
# literal strings ADR-083's Interface Contracts section uses, independent of
# the actual --home-root/--repo-root passed on this run.
SCOPE_DISPLAY = {
    'stack': 'config/aliases.json',
    'org': '~/.claude/config/aliases.org.json',
}


def fail(msg, code=3):
    print(f'gen-alias-stubs: {msg}', file=sys.stderr)
    sys.exit(code)


def load_source(path, required):
    """Returns the parsed {"version":1,"aliases":{...}} doc. A missing file
    is {} (not an error) when not required; a present-but-malformed file
    always fails hard (D13: both phase-1 sources are shared/committed)."""
    if not os.path.isfile(path):
        if required:
            fail(f'required source missing: {path}')
        return {'version': 1, 'aliases': {}}
    try:
        with open(path) as f:
            doc = json.load(f)
    except (OSError, json.JSONDecodeError) as e:
        fail(f'malformed source {path}: {e}')
    if not isinstance(doc, dict):
        fail(f'malformed source {path}: top level must be an object')
    extra = set(doc.keys()) - ALLOWED_TOP
    if extra:
        fail(f'{path}: unknown top-level field(s): {sorted(extra)}')
    if doc.get('version') != 1:
        fail(f'{path}: version must be 1')
    words = doc.get('aliases')
    if not isinstance(words, dict):
        fail(f'{path}: "aliases" must be an object')
    return doc


def validate_entries(path, scope, words, skill_ids, all_capability_ids):
    """Per-entry schema validation (ADR-083 D13). Returns a dict of
    word -> normalized entry (or {'disable': True})."""
    out = {}
    for word, entry in words.items():
        if not WORD_RE.match(word):
            fail(f'{path}: word "{word}" fails ^[a-z][a-z0-9-]{{0,31}}$')
        if not isinstance(entry, dict):
            fail(f'{path}: entry for "{word}" must be an object')
        extra = set(entry.keys()) - ALLOWED_ENTRY
        if extra:
            fail(f'{path}: "{word}" has unknown field(s): {sorted(extra)}')
        if entry.get('disable'):
            if entry.get('disable') is not True or (set(entry.keys()) - {'disable'}):
                fail(f'{path}: "{word}".disable must be the only field, set to true')
            out[word] = {'disable': True}
            continue
        target = entry.get('target')
        if not target:
            fail(f'{path}: "{word}" has no target and is not disabled')
        help_kind = entry.get('help', 'suffix')
        if help_kind not in ('suffix', 'row'):
            fail(f'{path}: "{word}".help must be "suffix" or "row"')
        # A promoted alias (help:"row", stack-only) synthesizes its own
        # capabilities[] entry in the registry (ADR-083 D10) — gen-capability-
        # registry.sh already refuses to build that registry if the word
        # collided with any *other* capability first, so by the time a
        # committed registry exists, a row entry's own id is guaranteed to
        # be self-referential, not a real collision. Checking it here would
        # make a promoted alias fail against its own synthesized reflection
        # every single run (ADR-084 D7).
        self_referential = help_kind == 'row' and scope == 'stack'
        if word in all_capability_ids and not self_referential:
            fail(f'{path}: word "{word}" collides with an existing capability id')
        # D13 rules 2/3 — target must be a real kind:"skill" capability, and
        # (since capabilities[] never carries an alias word, D9) this same
        # check is what makes a chain (target itself an alias) impossible.
        # A prior fix (40d6111) for the self-collision case above dropped
        # this check entirely while restructuring — restored here. Every
        # value that reaches render_stub's `alias_of: {target}` line is
        # therefore drawn from this known-safe, disk/registry-derived set,
        # never raw org input — this is also half of the injection defense
        # below (target can't carry a newline if it can't exist outside
        # skill_ids at all).
        if target not in skill_ids:
            fail(f'{path}: "{word}" target "{target}" is not a kind:"skill" capability (or is itself an alias — chains are not allowed)')
        if help_kind == 'row' and scope != 'stack':
            fail(f'{path}: "{word}" sets help:"row" outside the stack source — promoted aliases are stack-only')
        desc = entry.get('description')
        # Single-line requirement (Interface contracts: `.description` is
        # "single-line string") applies to EVERY help kind, not just "row" —
        # an org's aliases.org.json is untrusted external content, and
        # description/tools are interpolated verbatim into the generated
        # SKILL.md's frontmatter ahead of this script's own trusted
        # user-invocable/model-invocable lines. An embedded newline plus a
        # literal `---` would terminate that YAML block early and let the
        # rest of the entry's value forge frontmatter the model then reads
        # as trusted config (e.g. flipping model-invocable). Every string
        # field is confined to exactly one physical output line by
        # rejecting \n/\r outright, so no field can ever introduce a new
        # line into the emitted file at all.
        if desc is not None and ('\n' in desc or '\r' in desc):
            fail(f'{path}: "{word}".description must be a single line (no embedded newline)')
        if help_kind == 'row':
            if not desc:
                fail(f'{path}: "{word}" has help:"row" and needs a single-line description')
        mode = entry.get('mode')
        if mode is not None:
            if not MODE_RE.match(mode):
                fail(f'{path}: "{word}".mode "{mode}" fails ^[a-z][a-z0-9-]{{0,15}}$')
            if not target_declares_mode(target, mode):
                fail(f'{path}: "{word}" sets mode "{mode}" but target "{target}" does not declare it under "## Display modes"')
        tools = entry.get('tools')
        if tools is not None and not isinstance(tools, str):
            fail(f'{path}: "{word}".tools must be a string')
        if tools is not None and ('\n' in tools or '\r' in tools):
            fail(f'{path}: "{word}".tools must be a single line (no embedded newline)')
        out[word] = {
            'target': target,
            'mode': mode,
            'help': help_kind,
            'description': entry.get('description'),
            'tools': tools,
        }
    return out


def target_skill_md_path(target):
    # Repo checkout first: it's the source of truth for stack skills (a tier
    # install is a plain copy of it), and --stack-only must validate the
    # checkout alone, with no dependency on this machine's ~/.claude state
    # (its own doc comment: "no --home-root needed"). Falling back to
    # HOME_ROOT still resolves an org-only target that exists only as an
    # installed copy, never shipped in this repo.
    for root in (REPO_ROOT, HOME_ROOT):
        p = os.path.join(root, 'skills', target, 'SKILL.md')
        if os.path.isfile(p):
            return p
    return None


def target_declares_mode(target, mode):
    path = target_skill_md_path(target)
    if not path:
        return False
    with open(path) as f:
        text = f.read()
    m = re.search(r'^## Display modes\s*$(.*?)(^## |\Z)', text, re.MULTILINE | re.DOTALL)
    if not m:
        return False
    section = m.group(1)
    return re.search(rf'\b{re.escape(mode)}\b', section) is not None


# ─── --stack-only: validate the committed stack source, write nothing ───────

if STACK_ONLY:
    reg_path = os.path.join(REPO_ROOT, 'config', 'capability-registry.json')
    skill_ids = set()
    all_ids = set()
    if os.path.isfile(reg_path):
        with open(reg_path) as f:
            reg = json.load(f)
        for c in reg.get('capabilities', []):
            all_ids.add(c['id'])
            if c.get('kind') == 'skill':
                skill_ids.add(c['id'])
    else:
        for md in glob.glob(os.path.join(REPO_ROOT, 'skills', '*', 'SKILL.md')):
            skill_ids.add(os.path.basename(os.path.dirname(md)))
        all_ids |= skill_ids
        for md in glob.glob(os.path.join(REPO_ROOT, 'agents', '*.md')):
            all_ids.add(os.path.basename(md)[:-3])

    stack_path = os.path.join(REPO_ROOT, 'config', 'aliases.json')
    stack_doc = load_source(stack_path, required=True)
    validate_entries(stack_path, 'stack', stack_doc['aliases'], skill_ids, all_ids)
    print('OK: config/aliases.json is valid')
    sys.exit(0)

# ─── Full run: resolve, materialize, purge ───────────────────────────────────

scope_order = [s.strip() for s in SOURCES_ARG.split(',') if s.strip()]
if not scope_order:
    fail('--sources must name at least one scope', code=2)
for s in scope_order:
    if s not in SCOPE_DISPLAY:
        fail(f'--sources names an unrecognized scope: "{s}" (phase 1 knows only org, stack)', code=2)

reg_path = os.path.join(HOME_ROOT, 'config', 'capability-registry.json')
if not os.path.isfile(reg_path):
    reg_path = os.path.join(REPO_ROOT, 'config', 'capability-registry.json')
if not os.path.isfile(reg_path):
    fail(f'no capability-registry.json found under {HOME_ROOT} or {REPO_ROOT}')
with open(reg_path) as f:
    registry = json.load(f)
caps = registry.get('capabilities', [])
all_capability_ids = {c['id'] for c in caps}
skill_ids = {c['id'] for c in caps if c.get('kind') == 'skill'}
skill_tier_min = {c['id']: c.get('tier_min', 0) for c in caps if c.get('kind') == 'skill'}
skill_summary = {c['id']: c.get('summary', '') for c in caps if c.get('kind') == 'skill'}

# Installed tier ceiling (D9: a stack alias whose target's tier_min exceeds
# the installed tier is not generated). Same fallback stack-help.sh already
# uses for a missing/absent install stamp — "assume everything is available"
# rather than invent a stricter default nothing else in the codebase uses.
installed_tier = 5
stamp_path = os.path.join(HOME_ROOT, '.stack-install.json')
if os.path.isfile(stamp_path):
    try:
        with open(stamp_path) as f:
            stamp = json.load(f)
        installed_tier = int(stamp.get('tier', 5))
    except (OSError, json.JSONDecodeError, ValueError, TypeError):
        installed_tier = 5

paths = {
    'org': os.path.join(HOME_ROOT, 'config', 'aliases.org.json'),
    'stack': os.path.join(HOME_ROOT, 'config', 'aliases.json'),
}

# First pass: which words the stack source promotes with help:"row" — org
# may never take one of these (D7/D13 rule 7), enforced defensively here as
# well as at the pack layer.
stack_doc_probe = load_source(paths['stack'], required=True)
promoted_stack_words = {
    w for w, e in stack_doc_probe['aliases'].items()
    if isinstance(e, dict) and e.get('help') == 'row'
}

validated_by_scope = {}
for scope in scope_order:
    path = paths[scope]
    doc = load_source(path, required=(scope == 'stack'))
    validated_by_scope[scope] = (path, validate_entries(path, scope, doc['aliases'], skill_ids, all_capability_ids))

# Rule 7, cross-scope: an org word may not equal a stack-promoted word.
if 'org' in validated_by_scope:
    org_path, org_words = validated_by_scope['org']
    for w in org_words:
        if w in promoted_stack_words:
            fail(f'{org_path}: "{w}" is a stack promoted alias — it cannot be repointed or disabled by a company source')

# Fold: first-declaration-wins, highest precedence first.
resolved = {}
for scope in scope_order:
    path, words = validated_by_scope[scope]
    for word, entry in words.items():
        if word in resolved:
            continue
        resolved[word] = {'scope': scope, 'source_path': path, **entry}

# Tier filter (stack only) + disable — build the final materialization set.
materialize = {}
for word, entry in resolved.items():
    if entry.get('disable'):
        continue
    if entry['scope'] == 'stack':
        tier_min = skill_tier_min.get(entry['target'], 0)
        if tier_min > installed_tier:
            continue
    materialize[word] = entry

# ─── Stub content ────────────────────────────────────────────────────────────

def default_description(target):
    summary = skill_summary.get(target, '')
    return f'Alias for /{target}. {summary}'.rstrip()


def render_stub(word, entry):
    target = entry['target']
    mode = entry.get('mode')
    help_kind = entry.get('help', 'suffix')
    tools = entry.get('tools')
    scope = entry['scope']
    source_display = SCOPE_DISPLAY[scope]

    description = entry.get('description') or default_description(target)

    lines = ['---', f'name: {word}', f'description: {description}', f'alias_of: {target}']
    if mode:
        lines.append(f'alias_mode: {mode}')
    if help_kind == 'row':
        lines.append('alias_help: row')
    lines.append('user-invocable: true')
    lines.append('model-invocable: false')
    if help_kind != 'row':
        lines.append('recommendable: false')
    if tools:
        lines.append(f'tools: {tools}')
    lines.append('---')
    lines.append(f'{HEADER_PREFIX}{scope} ({source_display}) — do not edit -->')
    lines.append('')

    if mode:
        lines.append(f'# /{word} → /{target} ({mode} face)')
        lines.append('')
        if help_kind == 'row':
            lines.append(
                f'Invoke the `{target}` skill and follow its instructions exactly, in\n'
                f'**{mode}** display mode. Read its `## Display modes` section in full and\n'
                f'follow it exactly — everything it names as running in `{mode}` mode, in\n'
                f'the order given, nothing else. That section is authoritative; do not\n'
                f'infer a shorter or longer list from any other part of the target skill.\n'
                f'Honour that mode\'s output budget and banned-word list. Print nothing\n'
                f'outside what that mode specifies.'
            )
        else:
            lines.append(
                f'Invoke the `{target}` skill and follow its instructions exactly, in\n'
                f'**{mode}** mode — see its `## Display modes` section.'
            )
    else:
        lines.append(f'# /{word} → /{target}')
        lines.append('')
        lines.append(f'Invoke the `{target}` skill and follow its instructions exactly.')

    return '\n'.join(lines) + '\n'


def has_header(skill_md_path):
    if not os.path.isfile(skill_md_path):
        return False
    with open(skill_md_path) as f:
        return HEADER_PREFIX in f.read()


def is_adoptable_legacy_stub(skill_md_path, word):
    """True iff skill_md_path is safe to take over as prior-generation build
    output, even though it lacks our D12 header — never true for a real
    user-authored skill. Migration note (post-2026-08-17 review): every
    release before this script existed shipped ~/.claude/skills/{hi,hello,
    bye,goodbye,docs,carbonet}/SKILL.md as hand-written files declaring
    `alias_of: <target>` in frontmatter — the ADR-065/D65-D convention this
    script's own generated stubs still use. That field is not something any
    real, hand-authored skill would ever declare; it existed only to be
    disk-scanned by the alias mechanism this ADR replaces. Without this,
    `gen-alias-stubs.sh` would refuse to (re)materialize those exact six
    words on the very first `update.sh` after this branch ships — the D13
    rule-8 refuse-overwrite guard firing against the project's own prior
    output instead of a user's content, hard-aborting every upgrading
    install under `install.sh`'s `set -e`. `name:` must match the word this
    run is about to write there, so a coincidental hand-authored file at
    this exact path that happens to declare an unrelated `alias_of:` is
    never silently adopted."""
    if not os.path.isfile(skill_md_path):
        return False
    with open(skill_md_path) as f:
        text = f.read()
    fm = re.match(r'^---\n(.*?)\n---', text, re.DOTALL)
    if not fm:
        return False
    fm_text = fm.group(1)
    if not re.search(r'^alias_of:\s*\S', fm_text, re.MULTILINE):
        return False
    name_m = re.search(r'^name:\s*(.+?)\s*$', fm_text, re.MULTILINE)
    if name_m and name_m.group(1) != word:
        return False
    return True


def atomic_write(dest, content):
    # Non-atomic open(dest, 'w') truncates before writing — a disk-full,
    # interrupt, or kill mid-write can leave a partial/empty SKILL.md a
    # session might then read as a skill definition. Write to a sibling
    # temp file and os.replace (atomic on the same filesystem, which a
    # same-directory temp file always is).
    tmp = dest + '.tmp'
    with open(tmp, 'w') as f:
        f.write(content)
    os.replace(tmp, dest)


# ─── Plan: what would be written, what would be purged ──────────────────────

skills_root = os.path.join(HOME_ROOT, 'skills')
existing_generated = set()
for md in glob.glob(os.path.join(skills_root, '*', 'SKILL.md')):
    word = os.path.basename(os.path.dirname(md))
    if has_header(md):
        existing_generated.add(word)

# Refuse-overwrite check (D13 rule 8): a dir exists at the stub path without
# our header. Checked BEFORE any write, across every materialize target, so
# one bad collision blocks the whole run rather than half-landing. A
# pre-branch hand-written stub for one of these exact words is adopted
# (overwritten) instead of refused — see is_adoptable_legacy_stub.
adopting = set()
for word in materialize:
    dest = os.path.join(skills_root, word, 'SKILL.md')
    if os.path.exists(dest) and not has_header(dest):
        if is_adoptable_legacy_stub(dest, word):
            adopting.add(word)
        else:
            fail(f'refusing to overwrite {dest} — it exists and was not generated by this script')
    if os.path.isdir(os.path.join(skills_root, word)) and not os.path.isfile(dest) and os.listdir(os.path.join(skills_root, word)):
        fail(f'refusing to write {dest} — {os.path.dirname(dest)} exists with unrelated content')

writes = {}
for word, entry in materialize.items():
    content = render_stub(word, entry)
    dest = os.path.join(skills_root, word, 'SKILL.md')
    if os.path.isfile(dest) and word not in adopting:
        with open(dest) as f:
            current = f.read()
        if current == content:
            continue
    writes[word] = (dest, content)

pending_path = os.path.join(HOME_ROOT, 'state', 'alias-pending-purge.json')
prior_pending = []
if os.path.isfile(pending_path):
    try:
        with open(pending_path) as f:
            raw_pending = json.load(f).get('pending_purge', [])
        # Every other external input this script reads is WORD_RE-constrained
        # before it can influence a filesystem path — this state file is the
        # one exception, and it flows straight into shutil.rmtree below via
        # os.path.join(skills_root, word). Nothing writes this file except
        # this script itself today (packs never touch state/), so this isn't
        # reachable from the org/pack input surface — filtered anyway, same
        # discipline as every other word this script trusts.
        prior_pending = [w for w in raw_pending if isinstance(w, str) and WORD_RE.match(w)]
    except (OSError, json.JSONDecodeError):
        prior_pending = []

purge_candidates = sorted((existing_generated - set(materialize.keys())) | set(prior_pending))
# A word can only be purged if it is still not materialized this run — a
# previously-deferred purge whose word was re-added since must be dropped
# from the pending set without deleting anything.
purge_now = [w for w in purge_candidates if w not in materialize]

if NO_PURGE:
    deferred = sorted(set(purge_now) | set(prior_pending))
    to_delete = []
else:
    to_delete = purge_now
    deferred = []

# ─── --check: report drift, write nothing ───────────────────────────────────

if CHECK:
    drift = list(writes.keys()) + to_delete
    if drift:
        for w in writes:
            verb = 'adopt' if w in adopting else 'write'
            print(f'would {verb} /{w}')
        for w in to_delete:
            print(f'would purge /{w}')
        sys.exit(1)
    print('OK: alias stubs are fresh')
    sys.exit(0)

# ─── Execute: write-then-purge (D16 rule 3) ─────────────────────────────────

import shutil

for word, (dest, content) in writes.items():
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    atomic_write(dest, content)
    label = 'alias-adopt' if word in adopting else 'alias-write'
    print(f'  [{label}] /{word} -> {dest}')

for word in to_delete:
    d = os.path.join(skills_root, word)
    if not os.path.isdir(d):
        continue
    # A generated stub directory only ever contains the one SKILL.md this
    # script wrote — rmtree-ing the whole directory is safe only when that
    # still holds. If something else has since been placed alongside it,
    # remove just the generated file (un-stub it) and leave the rest, rather
    # than silently destroying content this script never created.
    contents = os.listdir(d)
    if contents == ['SKILL.md']:
        shutil.rmtree(d)
        print(f'  [alias-purge] /{word}')
    else:
        os.remove(os.path.join(d, 'SKILL.md'))
        print(f'  [alias-purge] /{word} (SKILL.md removed; directory kept — contains other content: {sorted(contents)})')

os.makedirs(os.path.dirname(pending_path), exist_ok=True)
if deferred:
    with open(pending_path, 'w') as f:
        json.dump({'pending_purge': deferred}, f, indent=2)
        f.write('\n')
    print(f'  [alias-purge-deferred] {", ".join("/" + w for w in deferred)} (STACK_INSESSION or --no-purge)')
elif os.path.isfile(pending_path):
    os.remove(pending_path)

print(f'Wrote {len(writes)} alias stub(s), purged {len(to_delete)}, deferred {len(deferred)}.')
sys.exit(0)
