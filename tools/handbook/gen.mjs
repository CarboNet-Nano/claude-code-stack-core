const HEADER = '<!-- GENERATED by tools/handbook/gen.mjs — edit the sources, not this file -->';
const TOC_START = '<!-- gen:toc:start -->';
const TOC_END = '<!-- gen:toc:end -->';
const GROUP_ORDER = ['session lifecycle', 'safety gates', 'metered tools', 'dev workflow', 'personal'];

function die(code, msg) { console.error(`FAIL: ${msg}`); process.exit(code); }

// ---------- args ----------
const args = process.argv.slice(2);
let repoRoot = null, check = false, deck = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--repo-root') { repoRoot = args[++i]; }
  else if (args[i] === '--check') { check = true; }
  else if (args[i] === '--deck') { deck = true; }
  else { console.error(`FAIL: unknown argument: ${args[i]}`); process.exit(2); }
}
if (!repoRoot) { console.error('FAIL: --repo-root is required'); process.exit(2); }

// ---------- roster-root resolution (spec 2026-08-16-handbook-portable-design) ----------
// R is the roster SOURCE root only; repoRoot stays the read/write root for
// docs/handbook/** in every mode.
function setMissing(root) {
  const missing = [];
  const agentsDir = join(root, 'agents');
  if (!existsSync(agentsDir) || !readdirSync(agentsDir).some(f => f.endsWith('.md'))) missing.push('agents/ (with at least one .md)');
  for (const rel of ['config/model-routing.json', 'config/capability-registry.json', 'tools/handbook/groups.json']) {
    if (!existsSync(join(root, rel))) missing.push(rel);
  }
  if (!existsSync(join(root, 'skills'))) missing.push('skills/');
  return missing;
}
function resolveRosterRoot() {
  const env = process.env.HANDBOOK_ROSTER_ROOT;
  if (env) {
    if (!isAbsolute(env)) die(3, `HANDBOOK_ROSTER_ROOT must be an absolute path: ${env}`);
    const missing = setMissing(env);
    if (missing.length) die(3, `HANDBOOK_ROSTER_ROOT ${env} is missing: ${missing.join(', ')}`);
    return { root: env, cls: 'env' };
  }
  if (setMissing(repoRoot).length === 0) return { root: repoRoot, cls: 'repo' };
  const installed = join(homedir(), '.claude');
  const missing = setMissing(installed);
  if (missing.length) die(3, `no roster root: --repo-root lacks the source set and ${installed} is missing: ${missing.join(', ')}`);
  return { root: installed, cls: 'installed' };
}
const { root: rosterRoot, cls: rosterClass } = resolveRosterRoot();
const ROSTER_LINE = `<!-- roster: ${rosterClass} -->`;

// ---------- tiny YAML-subset frontmatter parser ----------
function parseFrontmatter(text, file) {
  if (!text.startsWith('---\n')) die(3, `${file}: no frontmatter`);
  const end = text.indexOf('\n---\n', 4);
  if (end === -1) die(3, `${file}: unterminated frontmatter`);
  const raw = text.slice(4, end + 1);
  const body = text.slice(end + 5);
  const fm = {};
  const lines = raw.split('\n');
  let curKey = null;        // block-list key awaiting "- " items
  let scalarKey = null;     // scalar key that may continue on indented lines
  for (const line of lines) {
    if (/^\s*$/.test(line)) continue;
    const list = line.match(/^\s+-\s+(.*)$/);
    if (list && curKey) { fm[curKey].push(list[1].trim()); continue; }
    const cont = line.match(/^\s+(\S.*)$/);
    if (cont && scalarKey) { fm[scalarKey] += ' ' + cont[1].trim(); continue; }
    const kv = line.match(/^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$/);
    if (!kv) die(3, `${file}: unparseable frontmatter line: ${line}`);
    const [, key, value] = kv;
    curKey = null; scalarKey = null;
    if (value === '' || value === '>-' || value === '>' || value === '|' || value === '|-') { fm[key] = value === '' ? [] : ''; if (value === '') curKey = key; else scalarKey = key; if (value === '') scalarKey = null; }
    else if (value === '[]') { fm[key] = []; }
    else { fm[key] = value.trim(); scalarKey = key; }
  }
  // a key with an empty [] that then received scalar continuations stays a list
  for (const k of Object.keys(fm)) if (typeof fm[k] === 'string') fm[k] = fm[k].trim();
  return { fm, body };
}

// ---------- loaders ----------
function loadJson(rel) {
  const p = join(rosterRoot, rel);
  if (!existsSync(p)) die(3, `missing source: ${rel}`);
  try { return JSON.parse(readFileSync(p, 'utf8')); }
  catch (e) { die(3, `${rel}: invalid JSON: ${e.message}`); }
}

function loadAgents() {
  const dir = join(rosterRoot, 'agents');
  const out = [];
  for (const f of readdirSync(dir).filter(f => f.endsWith('.md')).sort()) {
    const { fm, body } = parseFrontmatter(readFileSync(join(dir, f), 'utf8'), `agents/${f}`);
    const name = basename(f, '.md');
    if (fm.name && fm.name !== name) die(3, `agents/${f}: frontmatter name '${fm.name}' != filename`);
    if (!fm.description) die(3, `agents/${f}: missing description`);
    if (!fm.dispatch_when) die(3, `agents/${f}: missing dispatch_when`);
    out.push({ name, fm, body });
  }
  return out;
}

const routing = loadJson('config/model-routing.json');
const registry = loadJson('config/capability-registry.json');
const agents = loadAgents();
