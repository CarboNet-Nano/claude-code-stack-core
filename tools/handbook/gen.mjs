function genHeader() { return `${HEADER}\n${ROSTER_LINE}`; }

// ---------- agent pages ----------
function agentPage(a) {
  const r = assignments[a.name];
  const reg = registryByld.get(a.name);
  const orchestrator = r.orchestrated_by
    ? `\`${r.orchestrated_by}\` (from model-routing \`orchestrated_by\`)`
    : `\`${a.fm.model || 'unspecified'}\` (from agent frontmatter \`model\`)`;
  const rungs = [];
  if (r.escalation) rungs.push(`escalation: \`${r.escalation}\``);
  if (r.routine_primary) rungs.push(`routine primary: \`${r.routine_primary}\``);
  if (r.routine_escalation) rungs.push(`routine escalation: \`${r.routine_escalation}\``);
  if (a.fm.escalation_model) rungs.push(`frontmatter escalation model: \`${a.fm.escalation_model}\``);

  const escFm = Array.isArray(a.fm.escalation_triggers) ? a.fm.escalation_triggers : (a.fm.escalation_triggers ? [a.fm.escalation_triggers] : []);
  const escRouting = Array.isArray(r.escalation_triggers) ? r.escalation_triggers : [];

  const refuses = (a.fm.forbidden_invokes || []).length
    ? (a.fm.forbidden_invokes).map(x => `- never invokes \`${x}\``).join('\n')
    : 'Not stated in source.';
  const pairs = (a.fm.allowed_invokes || []).length
    ? (a.fm.allowed_invokes).map(x => `- may invoke \`${x}\``).join('\n')
    : 'Not stated in source.';

  const firstPara = a.body.split(/\n\s*\n/).map(s => s.trim()).filter(s => s && !s.startsWith('#'))[0] || '';

  let out = `${genHeader()}\n# ${a.name}\n\n## Job spec\n\n${a.fm.description}\n`;
  if (firstPara) out += `\n${firstPara}\n`;
  out += `\n## When dispatched\n\n${a.fm.dispatch_when} (available from tier ${reg.tier_min}).\n`;
  out += `\n## Model & effort\n\n- Orchestrator: ${orchestrator}\n- Engine: \`${r.primary}\`${r.effort ? ` at \`${r.effort}\` effort` : ''}\n`;
  if (rungs.length) out += `- Fallback rungs: ${rungs.join(' · ')}\n`;
  if (escFm.length || escRouting.length) {
    out += `\n## Escalation\n\n`;
    if (escFm.length) out += `Frontmatter triggers (free text):\n${escFm.map(t => `- ${t}`).join('\n')}\n`;
    if (escRouting.length) {
      out += `\nRouting triggers (domain-mode, evidence verbatim):\n`;
      for (const t of escRouting) out += `- \`${t.domain_mode || 'unspecified'}\` → \`${t.primary || ''}\`${t.effort ? ` at \`${t.effort}\`` : ''}${t.evidence ? ` — ${t.evidence}` : ''}\n`;
    }
  }
  out += `\n## Refuses\n\n${refuses}\n\n## Pairs\n\n${pairs}\n`;
  out += `\n## Tools\n\n${a.fm.tools ? `\`${a.fm.tools}\`` : 'Not stated in source.'}\n`;
  return out;
}

// ---------- skills glossary ----------
function glossary() {
  const groupsPath = join(rosterRoot, 'tools/handbook/groups.json');
  if (!existsSync(groupsPath)) die(3, 'missing tools/handbook/groups.json');
  let groups;
  try { groups = JSON.parse(readFileSync(groupsPath, 'utf8')); }
  catch (e) { die(3, `tools/handbook/groups.json: invalid JSON: ${e.message}`); }

  const skills = registry.capabilities.filter(c => c.kind === 'skill').sort((x, y) => x.id.localeCompare(y.id));
  const hooks = registry.capabilities.filter(c => c.kind === 'hook').sort((x, y) => x.id.localeCompare(y.id));

  const unmapped = skills.filter(s => !groups[s.id]).map(s => s.id);
  if (unmapped.length) die(3, `skills missing from tools/handbook/groups.json (add them): ${unmapped.join(', ')}`);
  const phantom = Object.keys(groups).filter(k => !skills.some(s => s.id === k));
  if (phantom.length) die(3, `phantom keys in tools/handbook/groups.json (remove them): ${phantom.join(', ')}`);
  const badGroup = Object.entries(groups).filter(([, v]) => !GROUP_ORDER.includes(v.group));
  if (badGroup.length) die(3, `invalid group values in groups.json: ${badGroup.map(([k, v]) => `${k}=${v.group}`).join(', ')}`);

  let fallbackCount = 0;
  function skillDescription(id) {
    const p = join(rosterRoot, 'skills', id, 'SKILL.md');
    if (!existsSync(p)) { fallbackCount++; return null; }
    const { fm } = parseFrontmatter(readFileSync(p, 'utf8'), `skills/${id}/SKILL.md`);
    return fm.description || null;
  }

  let body = '';
  for (const g of GROUP_ORDER) {
    const members = skills.filter(s => groups[s.id].group === g);
    if (!members.length) continue;
    body += `\n## ${g[0].toUpperCase()}${g.slice(1)}\n`;
    for (const s of members) {
      const desc = skillDescription(s.id) || s.summary;
      const slash = s.invocation && s.invocation.slash ? ` (\`${s.invocation.slash}\`)` : '';
      body += `\n### ${s.id}${slash}\n\n${desc}\n\n- Touches: ${groups[s.id].touches}\n- Available from tier ${s.tier_min}.${s.user_invocable === false ? ' Not directly user-invocable.' : ''}\n`;
    }
  }
  body += `\n## Hooks (automatic, not invoked by people)\n\nHooks run on harness events (session start, tool calls, stops) without\nanyone invoking them.\n\n| Hook | What it does |\n|---|---|\n`;
  for (const h of hooks) body += `| ${h.id} | ${h.summary} |\n`;

  let intro = `${genHeader()}\n# Skills glossary\n\nEvery skill in the stack, grouped by what it is for. A skill (a packaged\nworkflow you or the model can invoke, usually as a slash command) is listed\nwith what it does, when to use it, and what it touches. Generated from\n\`config/capability-registry.json\`, \`skills/*/SKILL.md\`, and\n\`tools/handbook/groups.json\`.\n`;
  if (fallbackCount > 0 && rosterClass !== 'repo') {
    intro += `\nSome descriptions are abbreviated: ${fallbackCount} skill(s) are not present in the resolved roster root, so their registry summary is shown instead.\n`;
  }
  return intro + body;
}

// ---------- README TOC ----------
function tocBlock() {
  const lines = ['- [Executive summary](00-executive-summary.md)',
    '- [Start here](01-start-here.md)',
    '- [Decision guide](02-decision-guide.md)',
    '- [Workflows in practice](03-workflows-in-practice.md)',
    '- [Trust and safety](04-trust-and-safety.md)',
    '- [Talk track](05-talk-track.md)',
    '- [The machinery](machinery/README.md)'];
  const machDir = join(repoRoot, 'docs/handbook/machinery');
  if (existsSync(machDir)) {
    for (const f of readdirSync(machDir).filter(f => f.endsWith('.md') && f !== 'README.md').sort()) {
      lines.push(`  - [${basename(f, '.md')}](machinery/${f})`);
    }
  }
  lines.push('- [Agent pages (appendix)](agents/)');
  lines.push('- [Skills glossary (appendix)](skills-glossary.md)');
  return lines.join('\n');
}

function spliceToc(readme) {
  const starts = readme.split('\n').filter(l => l.trim() === TOC_START).length;
  const ends = readme.split('\n').filter(l => l.trim() === TOC_END).length;
  if (starts !== 1 || ends !== 1) die(3, `docs/handbook/README.md: expected exactly one ${TOC_START}/${TOC_END} pair (found ${starts}/${ends})`);
  const si = readme.indexOf(TOC_START), ei = readme.indexOf(TOC_END);
  if (ei < si) die(3, 'docs/handbook/README.md: TOC markers reversed');
  return readme.slice(0, si + TOC_START.length) + '\n' + tocBlock() + '\n' + readme.slice(ei);
}

// ---------- deck parser (fence-aware line scanner, spec N3) ----------
function parseSlides(text, file) {
  const lines = text.split('\n');
  const slides = [];
  let fence = null; // {char, len}
  let cur = null;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const fenceMatch = line.match(/^ {0,3}(`{3,}|~{3,})/);
    if (fenceMatch) {
      const [, m] = fenceMatch;
      if (!fence) fence = { char: m[0], len: m.length };
      else if (m[0] === fence.char && m.length >= fence.len && line.trim() === m) fence = null;
      continue;
    }
    if (fence || /^ {4,}\S/.test(line) && !cur) continue; // inside fenced or indented code
    const open = line.match(/^<!-- slide:\s*(.+?)\s*-->$/);
    const close = /^<!-- \/slide -->$/.test(line.trim());
    if (open) {
      if (cur) die(3, `${file}:${i + 1}: nested slide block`);
      if (!open[1]) die(3, `${file}:${i + 1}: empty slide title`);
      cur = { title: open[1], takeaway: null, bullets: [], notes: null, _inNotes: false };
      continue;
    }
    if (close) {
      if (!cur) die(3, `${file}:${i + 1}: closing marker without open`);
      if (!cur.takeaway) die(3, `${file}: slide '${cur.title}': missing takeaway`);
      delete cur._inNotes;
      slides.push(cur); cur = null;
      continue;
    }
    if (!cur) continue;
    const kw = line.match(/^(takeaway|notes):\s*(.*)$/i);
    if (kw) {
      const key = kw[1].toLowerCase();
      if (key === 'takeaway') { cur.takeaway = kw[2].trim(); cur._inNotes = false; }
      else {
        if (cur.notes !== null) die(3, `${file}: slide '${cur.title}': more than one notes block`);
        cur.notes = kw[2].trim(); cur._inNotes = true;
      }
      continue;
    }
    if (/^-\s+/.test(line.trim())) { cur.bullets.push(line.trim().replace(/^-\s+/, '')); cur._inNotes = false; continue; }
    if (/^\s*$/.test(line)) { cur._inNotes = false; continue; }
    if (cur._inNotes) { cur.notes += ' ' + line.trim(); continue; }
    // narrative prose inside a slide block that is neither keyword nor bullet: allowed, handbook-only
  }
  if (cur) die(3, `${file}: unclosed slide block '${cur.title}'`);
  if (!slides.length) die(3, `${file}: no slide blocks found`);
  return slides;
}

function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;'); }

function renderDeckHtml(slides) {
  const slideDivs = slides.map((s, i) => `    <section class="slide${i === 0 ? ' active' : ''}" data-i="${i}">
      <h1>${esc(s.title)}</h1>
      <p class="takeaway">${esc(s.takeaway)}</p>
      ${s.bullets.length ? `<ul>\n${s.bullets.map(b => `        <li>${esc(b)}</li>`).join('\n')}\n      </ul>` : ''}
      ${s.notes ? `<aside class="notes">${esc(s.notes)}</aside>` : ''}
    </section>`).join('\n');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Claude Code Stack</title>
<style>
  :root { --bg:#ffffff; --fg:#1a1a2e; --accent:#4f46e5; --muted:#6b7280; --card:#f4f4f8; }
  @media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { --bg:#14181f; --fg:#e8e8f0; --accent:#8b8bf5; --muted:#9ca3af; --card:#1e242e; } }
  :root[data-theme="dark"] { --bg:#14181f; --fg:#e8e8f0; --accent:#8b8bf5; --muted:#9ca3af; --card:#1e242e; }
  * { box-sizing:border-box; margin:0; }
  body { background:var(--bg); color:var(--fg); font:18px/1.5 -apple-system,'Segoe UI',sans-serif; height:100vh; overflow:hidden; }
  .slide { display:none; flex-direction:column; justify-content:center; gap:1.2rem; height:100vh; padding:8vh 12vw; }
  .slide.active { display:flex; }
  h1 { font-size:2.6rem; line-height:1.15; }
  .takeaway { font-size:1.4rem; color:var(--accent); font-weight:600; max-width:34ch; }
  ul { padding-left:1.2rem; display:grid; gap:.5rem; font-size:1.15rem; max-width:60ch; }
  .notes { display:none; background:var(--card); color:var(--muted); padding:1rem; border-radius:8px; font-size:.95rem; max-width:70ch; }
  body.show-notes .notes { display:block; }
  .hud { position:fixed; bottom:1rem; right:1.2rem; color:var(--muted); font-size:.85rem; }
  .hint { position:fixed; bottom:1rem; left:1.2rem; color:var(--muted); font-size:.85rem; }
</style>
</head>
<body>
${slideDivs}
  <div class="hud"><span id="pos">1</span>/${slides.length}</div>
  <div class="hint">←/→ navigate · N notes</div>
<script>
  var i = 0, n = ${slides.length};
  var slides = document.querySelectorAll('.slide');
  function show(k) { i = Math.max(0, Math.min(n - 1, k)); slides.forEach(function(s, j) { s.classList.toggle('active', j === i); }); document.getElementById('pos').textContent = i + 1; }
  addEventListener('keydown', function(e) {
    if (e.key === 'ArrowRight' || e.key === ' ' || e.key === 'PageDown') show(i + 1);
    else if (e.key === 'ArrowLeft' || e.key === 'PageUp') show(i - 1);
    else if (e.key === 'n' || e.key === 'N') document.body.classList.toggle('show-notes');
  });
  var tx = null;
  addEventListener('touchstart', function(e) { tx = e.changedTouches[0].clientX; });
  addEventListener('touchend', function(e) { if (tx === null) return; var dx = e.changedTouches[0].clientX - tx; if (dx < -40) show(i + 1); if (dx > 40) show(i - 1); tx = null; });
</script>
</body>
</html>
`;
}

// ---------- output assembly ----------
function generateAll(outRoot) {
  const files = new Map(); // rel path -> content
  for (const a of agents) files.set(`docs/handbook/agents/${a.name}.md`, agentPage(a));
  files.set('docs/handbook/skills-glossary.md', glossary());

  const readmePath = join(repoRoot, 'docs/handbook/README.md');
  if (existsSync(readmePath)) files.set('docs/handbook/README.md', spliceToc(readFileSync(readmePath, 'utf8')));

  if (deck || check) {
    const execPath = join(repoRoot, 'docs/handbook/00-executive-summary.md');
    if (existsSync(execPath)) {
      const slides = parseSlides(readFileSync(execPath, 'utf8'), 'docs/handbook/00-executive-summary.md');
      files.set('docs/handbook/deck/slides.json', JSON.stringify(slides, null, 2) + '\n');
      if (deck && !check) files.set('docs/handbook/deck/index.html', renderDeckHtml(slides));
    } else if (deck && !check) {
      console.log('NOT-EXECUTED: deck (no docs/handbook/00-executive-summary.md)');
    }
  }

  return files;
}

function writeFiles(files, outRoot) {
  for (const [rel, content] of files) {
    const p = join(outRoot, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  }
}

const CHECKED = (rel) => rel !== 'docs/handbook/deck/index.html'; // committed artifacts only

if (check) {
  const tmp = mkdtempSync(join(tmpdir(), 'handbook-check-'));
  try {
    const files = generateAll(tmp);
    writeFiles(files, tmp);
    let drift = 0;
    for (const [rel] of files) {
      if (!CHECKED(rel)) continue;
      const committed = join(repoRoot, rel);
      if (!existsSync(committed)) { console.error(`FAIL: ${rel} (missing — run gen.mjs)`); drift++; continue; }
      if (readFileSync(committed, 'utf8') !== readFileSync(join(tmp, rel), 'utf8')) { console.error(`FAIL: ${rel} (drift — run gen.mjs)`); drift++; continue; }
      console.log(`OK: ${rel}`);
    }
    // orphan detection: generated agent pages with no source
    const genDir = join(repoRoot, 'docs/handbook/agents');
    if (existsSync(genDir)) {
      for (const f of readdirSync(genDir).filter(f => f.endsWith('.md')).sort()) {
        if (!files.has(`docs/handbook/agents/${f}`)) { console.error(`FAIL: docs/handbook/agents/${f} (orphan — run gen.mjs)`); drift++; }
      }
    }
    process.exit(drift ? 1 : 0);
  } finally { rmSync(tmp, { recursive: true, force: true }); }
}

// write mode: header guard BEFORE any write, then write, then orphan purge
const files = generateAll(repoRoot);
for (const [rel] of files) {
  const p = join(repoRoot, rel);
  if (rel === 'docs/handbook/README.md' || rel === 'docs/handbook/deck/slides.json' || rel === 'docs/handbook/deck/index.html') continue;
  const existing = existsSync(p) ? readFileSync(p, 'utf8') : null;
  if (existing !== null && !existing.startsWith(HEADER)) {
    die(4, `${rel} exists without the GENERATED header — refusing to overwrite a hand-edited file`);
  }
}
writeFiles(files, repoRoot);
