#!/usr/bin/env node
// Handbook generator (ADR-081). One driver for every generated handbook
// artifact: agent pages, skills glossary, README TOC, deck slides.json,
// deck index.html, and (via pptx.mjs, when its toolchain is installed)
// the PPTX. Spec: docs/superpowers/specs/2026-08-16-stack-handbook-design.md
//
// Exit codes: 0 ok · 1 drift/missing committed output (--check) · 2 usage ·
// 3 malformed source · 4 refused overwrite (target lacks GENERATED header).

